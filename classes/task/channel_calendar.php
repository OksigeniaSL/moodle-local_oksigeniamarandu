namespace local_oksigeniamarandu\task;

use local_oksigeniamarandu\local\calendar;

/**
 * Prepares the posts of the calendar of the site for the channel of Telegram: «This week» and «No class tomorrow».
 *
 * @package    local_oksigeniamarandu
 * @copyright  2026 Oksigenia SL <dev@oksigenia.cc>
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class channel_calendar extends \core\task\scheduled_task {
    /**
     * Name of the task, for the administration.
     *
     * @return string
     */
    public function get_name() {
        return get_string('task:channelcalendar', 'local_oksigeniamarandu');
    }

    /**
     * Prepares them; without a channel or a calendar, nothing.
     */
    public function execute() {
        $counts = calendar::prepare();
        if (array_sum($counts)) {
            mtrace('Marandu, the calendar of the channel: ' . json_encode($counts));
        }
    }
}
